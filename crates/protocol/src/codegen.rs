//! Protocol codegen: JSON Schema → Rust and TypeScript types.
//!
//! The JSON Schema under `protocol/schema/` is the source of truth. The
//! generated Rust types are committed to `crates/protocol/src/generated.rs`
//! and the generated TypeScript types to `packages/protocol/src/generated.ts`.
//! A freshness test fails when the committed output drifts from the schema.

use std::path::{Path, PathBuf};

/// Path of the schema, relative to the repository root.
pub const SCHEMA_RELPATH: &str = "protocol/schema/protocol.schema.json";

/// Resolve the repository root by walking up from a starting directory until
/// the protocol schema is found.
pub fn find_repo_root(start: &Path) -> Option<PathBuf> {
    let mut dir = Some(start);
    while let Some(current) = dir {
        if current.join(SCHEMA_RELPATH).is_file() {
            return Some(current.to_path_buf());
        }
        dir = current.parent();
    }
    None
}

/// Generate the Rust type definitions from the schema document.
pub fn generate_rust(schema_json: &str) -> anyhow::Result<String> {
    let schema: schemars::schema::RootSchema = serde_json::from_str(schema_json)?;
    let mut settings = typify::TypeSpaceSettings::default();
    settings.with_derive("PartialEq".to_string());
    let mut type_space = typify::TypeSpace::new(&settings);
    type_space.add_root_schema(schema)?;
    let mut out = String::new();
    out.push_str("// @generated by `cargo run -p fergents-protocol --bin gen-protocol`.\n");
    out.push_str(
        "// Do not edit by hand. Source of truth: protocol/schema/protocol.schema.json\n\n",
    );
    out.push_str(&type_space.to_stream().to_string());
    format_rust(&out)
}

/// Format Rust source with `rustfmt` (a required toolchain component), so the
/// committed codegen output is deterministic and readable.
pub fn format_rust(source: &str) -> anyhow::Result<String> {
    use std::io::Write;
    use std::process::{Command, Stdio};

    let mut child = Command::new("rustfmt")
        .args(["--edition", "2021", "--emit", "stdout", "--quiet"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| anyhow::anyhow!("failed to spawn rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .expect("stdin piped")
        .write_all(source.as_bytes())?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        anyhow::bail!(
            "rustfmt failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    Ok(String::from_utf8(output.stdout)?)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo_root() -> PathBuf {
        find_repo_root(Path::new(env!("CARGO_MANIFEST_DIR"))).expect("repo root")
    }

    fn schema_json() -> String {
        std::fs::read_to_string(repo_root().join(SCHEMA_RELPATH)).expect("read schema")
    }

    /// The committed generated output must match a fresh generation.
    #[test]
    fn generated_rust_is_fresh() {
        let expected = generate_rust(&schema_json()).expect("generate");
        let committed =
            std::fs::read_to_string(repo_root().join("crates/protocol/src/generated.rs"))
                .expect("read committed generated.rs");
        assert_eq!(
            committed.trim(),
            expected.trim(),
            "generated.rs is stale; run `cargo run -p fergents-protocol --bin gen-protocol`"
        );
    }
}
