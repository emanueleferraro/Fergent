//! The declarative kernel capability catalogue (Phase 2 spec Appendix D).
//!
//! The list is ordered so that a capability's dependencies always precede it,
//! which [`crate::CapabilityRegistry::seed`] relies on.

use crate::model::{Capability, DEFAULT_SOURCE};

fn capability(
    id: &str,
    name: &str,
    description: &str,
    dependencies: &[&str],
    default_enabled: bool,
    hot_toggle: bool,
) -> Capability {
    Capability {
        id: id.to_string(),
        name: name.to_string(),
        version: "0.1.0".to_string(),
        source: DEFAULT_SOURCE.to_string(),
        description: Some(description.to_string()),
        dependencies: dependencies.iter().map(|d| (*d).to_string()).collect(),
        resources: Vec::new(),
        default_enabled,
        hot_toggle,
        config: None,
    }
}

